"""Trace the thin skin strips between the falling strands at the left temple of ref 04 (trace-reference skill).

    ./harness/run.sh harness/franzi_hair/face_trace.py      # writes the face mask
    ./harness/run.sh harness/franzi_hair/slivers.py

The traced face (face_trace.py) is one component and leaves out the pale strip between the two diagonal strands, so the dome hair
painted black over skin the reference shows (found from the owner's note that the lid looked too thick: the thick part was hair).
The strip is two warm light components split by the brow line; they are joined, closed over the brow and fitted. Writes
ts/src/body-adult-temple-data.ts (head radii) and out/franzi_hair/slivers.png.
"""

from pathlib import Path
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

sys.path.insert(0, "/Users/henrik/git/anime-character-creator/.claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402

OX, OY, S = 660.0, 270.5, 175.7
a = np.array(Image.open("ref/franzi/04-bikini-fullbody.png").convert("RGBA")).astype(int)
rgb = a[..., :3]
lum = rgb.mean(2)
light = (lum > 150) & (a[..., 3] > 128) & (rgb[..., 0] > rgb[..., 2] + 15)
face = np.load("out/franzi_hair/face_mask.npy")
fd = ndimage.binary_dilation(face, iterations=3)
x0, y0, x1, y1 = 556, 244, 596, 310
m = np.zeros_like(light)
m[y0:y1, x0:x1] = light[y0:y1, x0:x1] & ~fd[y0:y1, x0:x1]
lab, n = ndimage.label(m)
keep = np.zeros_like(m)
for i in range(1, n + 1):
    ys, xs = np.nonzero(lab == i)
    if len(xs) >= 40:
        keep |= lab == i
keep = ndimage.binary_fill_holes(ndimage.binary_closing(keep, iterations=4))
keep = ndimage.binary_dilation(keep, iterations=1)  # to the centre of the black strand lines either side
pts = [((x - OX) / S, (y - OY) / S) for x, y in tl.boundary(keep)]
start, segs = tl.fit_closed(pts, 0.006)


def pt(q):
    return f"[{q[0]:.4f}, {q[1]:.4f}]"


body = ", ".join(f"[{pt(c)}, {pt(e)}]" for c, e in segs)
Path("ts/src/body-adult-temple-data.ts").write_text(
    "// Generated by harness/franzi_hair/slivers.py from ref 04. Do not edit by hand.\n"
    "// The pale strip of skin between the two falling strands at the viewer's-left temple, in head radii from the head centre.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    f"export const ADULT_TEMPLE_SKIN_L: Chain = [{pt(start)}, [{body}]];\n"
)
print("sliver segments", len(segs), "pixels", int(keep.sum()))
im = Image.open("ref/franzi/04-bikini-fullbody.png").convert("RGBA")
bg = Image.new("RGBA", im.size, "white")
bg.alpha_composite(im)
box = (530, 240, 640, 320)
Z = 8
img = bg.convert("RGB").crop(box).resize(((box[2] - box[0]) * Z, (box[3] - box[1]) * Z), Image.LANCZOS)
d = ImageDraw.Draw(img)
sp = [((OX + p[0] * S - box[0]) * Z, (OY + p[1] * S - box[1]) * Z) for p in tl.sample_chain(tuple(start), [(tuple(c), tuple(e)) for c, e in segs], 10)]
d.line(sp + [sp[0]], fill=(255, 0, 0), width=2)
img.save("out/franzi_hair/slivers.png")
