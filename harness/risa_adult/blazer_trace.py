"""Risa's blazer, from the flat blazer reference (ref/risa-adult/05-blazer.png): the lapels and their notch, the V of the opening, the front edge and its flared hem, the flap and the welt pockets,
the dart lines and the three gold buttons.

    ./harness/run.sh harness/risa_adult/blazer_trace.py

05 shows the garment alone, laid flat (no body), so there is nothing to register by the irises. It is fitted to our body by landmarks of its own (the same rule as the shirt: the torso and the sleeves
are NOT traced, they are built from our body's tables in ts/src/body-adult-blazer.ts, and only what the body cannot give is read off the picture, by hand from gridded zooms, 3x):

  vertical   the flat blazer's rows to head heights below the chin, through its own landmarks: the collar's top 0.0 (row 195), the lapel's top at the neck 0.12 (260), the first button 1.00 (733, a
             little under the V's point, as on the worn blazer of 01), the last button 1.48 (978), the hem 1.95 (1215). Cross-checked on 01 (registered, `registration.py`) where the buttons are at 0.93,
             1.20 and 1.42 and the hem at 1.87; the two agree to 0.1 H, the flat blazer is the more regular, and the hem is kept at 1.95 so the skirt's top is covered as in 01.
  horizontal the flat blazer's torso is 237 px each side of its centre (x 671) at the bust, which is our body's blazer half-width there (0.46 H of body plus 0.055 of ease) at 460 px per H. Things near
             the front (the V, the lapel, the front edge, the buttons) are in head heights at that scale. Things that live across the width (the pockets, the darts, the hem) are a fraction of the
             torso's half-width at their row, so they follow whatever width the body has.

Only the viewer's right half is read; the left is its mirror (as for the collar and the ribbon), except the welt pocket, which is on the right only. Writes ts/src/body-adult-blazer-data.ts.
"""

from pathlib import Path

CX = 671.0
S = 460.0  # px per head height, horizontally
YS = [(195, 0.0), (260, 0.12), (733, 1.00), (978, 1.48), (1215, 1.95)]
HW = [(600, 237), (750, 237), (790, 236), (830, 240), (870, 250), (910, 260), (950, 270), (990, 277), (1100, 302), (1170, 312), (1215, 314)]  # the flat torso's half-width by row


def lin(table, v):
    if v <= table[0][0]:
        (a0, b0), (a1, b1) = table[0], table[1]
        return b0 + (v - a0) * (b1 - b0) / (a1 - a0)
    for (a0, b0), (a1, b1) in zip(table, table[1:]):
        if v <= a1:
            return b0 + (v - a0) * (b1 - b0) / (a1 - a0)
    (a0, b0), (a1, b1) = table[-2], table[-1]
    return b1 + (v - a1) * (b1 - b0) / (a1 - a0)


def d_of(y):
    return lin(YS, y)


def hw(y):
    return lin(HW, y)


def near(pts):
    """Points in head heights at the blazer's scale: [x, d]."""
    return [((x - CX) / S, d_of(y)) for x, y in pts]


def frac(pts):
    """Points as a fraction of the torso's half-width at their row: [nx, d]."""
    return [((x - CX) / hw(y), d_of(y)) for x, y in pts]


# ---- the right half, in the flat blazer's pixels, read off the gridded zooms (blazer-grid-top.png, blazer-grid-low.png)
V_EDGE = [(758, 228), (759, 300), (753, 350), (746, 390), (736, 430), (727, 470), (716, 510), (705, 550), (693, 590), (681, 630), (670, 664)]  # the opening's edge, from the collar down to the V's point
COLLAR = [(764, 226), (800, 262), (840, 305), (871, 341)]  # the collar's outer edge down to its tip
NOTCH = [(871, 341), (838, 352), (806, 358)]  # the notch back in
LAPEL_TOP = [(806, 358), (850, 376), (892, 392)]  # the lapel's top edge out to its tip
LAPEL_FOLD = [(892, 392), (878, 425), (850, 470), (815, 520), (775, 570), (735, 610), (700, 640), (672, 668)]  # from the tip down the fold to the V's point
FRONT = [(683, 692), (682, 800), (681, 950), (681, 1100), (684, 1130), (692, 1165), (710, 1190)]  # the front edge: straight, then flaring out to the rounded corner
HEM = [(750, 1207), (800, 1215), (860, 1213), (920, 1203), (980, 1188)]  # the hem from the front corner out to the side
WELT = [(800, 484), (898, 481), (900, 511), (800, 514)]  # the breast welt pocket (right only)
FLAP = [(807, 914), (932, 898), (946, 962), (840, 978), (818, 977), (808, 965)]  # the lower flap pocket
FLAP_LINE = [(809, 920), (934, 904)]  # the line under the flap's top edge
DART = [(840, 625), (836, 720), (833, 800), (833, 912)]  # the dart line from the bust down to the pocket's flap
BUTTONS = [(662, 733), (662, 852), (662, 978)]
BUTTON_R = 15.0  # px; the buttons are 30 px across
BUTTONHOLE_LEN = 18.0  # the short slit left of each button


def pts(a, nd=4):
    return "[" + ", ".join(f"[{p[0]:.{nd}f}, {p[1]:.{nd}f}]" for p in a) + "]"


src = [
    "// Generated by harness/risa_adult/blazer_trace.py from the flat blazer of ref/risa-adult/05-blazer.png. Do not edit by hand.",
    "// The viewer's right half; the left is its mirror (the welt pocket is on the right only). [x, d]: x in head heights from the centre line, d in head heights below the chin.",
    "// `near` lists are in head heights at the blazer's scale; `frac` lists are [fraction of the torso's half-width at that depth, d], so they follow the body's width.",
    "",
    "export type Pt = readonly [number, number];",
    "",
]
for name, doc, data, kind in (
    ("BLAZER_V_EDGE", "The opening's edge from the collar down to the V's point.", V_EDGE, near),
    ("BLAZER_COLLAR", "The collar's outer edge down to its tip.", COLLAR, near),
    ("BLAZER_NOTCH", "The notch back in from the collar's tip.", NOTCH, near),
    ("BLAZER_LAPEL_TOP", "The lapel's top edge out to its tip.", LAPEL_TOP, near),
    ("BLAZER_LAPEL_FOLD", "The lapel's fold edge from its tip down to the V's point.", LAPEL_FOLD, near),
    ("BLAZER_FRONT", "The front edge: straight down, then flaring out to the rounded corner of the hem.", FRONT, near),
    ("BLAZER_HEM", "The hem from the front corner out to the side (fractions of the half-width).", HEM, frac),
    ("BLAZER_WELT", "The breast welt pocket, right only (fractions of the half-width).", WELT, frac),
    ("BLAZER_FLAP", "The lower flap pocket (fractions of the half-width).", FLAP, frac),
    ("BLAZER_FLAP_LINE", "The line under the flap's top edge (fractions of the half-width).", FLAP_LINE, frac),
    ("BLAZER_DART", "The dart line from the bust down to the pocket's flap (fractions of the half-width).", DART, frac),
):
    src.append(f"/** {doc} */\nexport const {name}: readonly Pt[] = {pts(kind(data))};\n")
btn = [(0.0, d_of(y)) for x, y in BUTTONS]
src.append(f"/** The three gold buttons' depths; they sit on the closure, a little left of the centre line (x -0.02 H). */\nexport const BLAZER_BUTTON_DEPTHS: readonly number[] = [{', '.join(f'{d:.4f}' for _, d in btn)}];\n")
src.append(f"/** The buttons' radius and the buttonhole slit's length, in head heights. */\nexport const BLAZER_BUTTON_R = {BUTTON_R / S:.4f};\nexport const BLAZER_BUTTONHOLE = {BUTTONHOLE_LEN / S:.4f};\n")
Path("ts/src/body-adult-blazer-data.ts").write_text("\n".join(src))
print("wrote ts/src/body-adult-blazer-data.ts; buttons at d", [round(d, 3) for _, d in btn], "hem d", round(d_of(1215), 3), "V point d", round(d_of(664), 3), "V top x", round((758 - CX) / S, 3))
