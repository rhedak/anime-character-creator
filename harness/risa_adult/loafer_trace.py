"""Risa's school loafer, from the legs close-up (ref/risa-adult/08-legs-closeup.png and its `brown-loafers` layers).

    PYTHONPATH=.claude/skills/trace-reference ./harness/run.sh harness/risa_adult/loafer_trace.py

08 shows the shoes whole (02 and 03 crop them). It is a close-up at its own scale (1152 x 1728), and Grok drew Risa's legs in the uniform images much shorter than this body's (hem to sole 1.85 head heights
against 3.1), so the loafer cannot be placed by registration: it is traced in its OWN coordinates and fitted to our foot in ts/src/body-adult-garments.ts. Coordinates: u across, in widths of the shoe from its
centre line, and t down, in lengths of the shoe from the top of its counters (the heel's back edge) to the sole's front.

The viewer's-left shoe is traced and symmetrised about its own centre line (the shoe faces nearly square on); the right shoe is its mirror.

  outline   the brown layer's silhouette, the notch at the top (where the sock shows in the shoe) included, eroded 2 px so the stroke's centre is on the edge
  sole      the dark band round the front, closed shape, a darker tone of the leather
  strap, slot, seam   read off a 5x gridded zoom (out/risa_adult/loafer-grid.png), the strap's two edges, the slot, and the seam round the oval below it
Writes ts/src/body-adult-loafer-data.ts.
"""

import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

sys.path.insert(0, ".claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402

lay = np.array(Image.open("ref/risa-adult/segments/08-legs-closeup/brown-loafers/brown-loafers-1.png"))[..., 3] > 200
img = np.array(Image.open("ref/risa-adult/08-legs-closeup.png").convert("RGB")).astype(float)
lum = img.mean(2)
lay = ndimage.binary_fill_holes(ndimage.binary_closing(lay, iterations=2)) & ~np.zeros_like(lay)
# keep the notch: fill_holes only fills enclosed holes, and the notch is open at the top
lab, n = ndimage.label(lay)
lay = lab == (1 + int(np.argmax(ndimage.sum(lay, lab, range(1, n + 1)))))
H, W = lay.shape
ys, xs = np.nonzero(lay)
y0, y1 = ys.min(), ys.max()
rows = range(1480, 1560)
axis = float(np.median([(np.nonzero(lay[y])[0].min() + np.nonzero(lay[y])[0].max()) / 2 for y in rows]))
mirror = np.zeros_like(lay)
for x in range(W):
    mx = int(round(2 * axis - x))
    if 0 <= mx < W:
        mirror[:, mx] = lay[:, x]
sym = lay | mirror
sym = ndimage.binary_opening(sym, structure=np.ones((3, 3)))
ys, xs = np.nonzero(sym)
y0, y1 = int(ys.min()), int(ys.max())
Wd = float(max(np.ptp(np.nonzero(sym[y])[0]) + 1 for y in range(y0, y1 + 1)))
Ln = float(y1 - y0 + 1)
print(f"axis {axis:.1f}, top {y0}, length {Ln:.0f}, widest {Wd:.0f}, aspect {Ln / Wd:.3f}")


def uv(x, y):
    return ((x - axis) / Wd, (y - y0) / Ln)


def chain(c):
    st, sg = c
    pt = lambda p: f"[{p[0]:.4f}, {p[1]:.4f}]"  # noqa: E731
    return f"[{pt(st)}, [{', '.join(f'[{pt(cc)}, {pt(e)}]' for cc, e in sg)}]]"


outline = tl.fit_closed([uv(x, y) for x, y in tl.boundary(ndimage.binary_erosion(sym, iterations=2))], 0.004)

# hand-read, in the reference's pixels about the axis (x - axis), y: from the 5x gridded zoom
STRAP_TOP = [(-73, 1405), (-48, 1388), (-22, 1380), (0, 1378), (22, 1380), (48, 1388), (73, 1403)]
STRAP_BOT = [(-68, 1446), (-40, 1436), (-20, 1424), (0, 1420), (20, 1424), (42, 1436), (68, 1450)]
SLOT = [(-42, 1405), (-22, 1398), (0, 1396), (22, 1398), (42, 1405), (22, 1404), (0, 1402), (-22, 1404)]
SEAM = [(-62, 1448), (-64, 1470), (-52, 1496), (-30, 1511), (0, 1517), (30, 1511), (52, 1496), (64, 1470), (62, 1448)]  # round the oval below the strap
SOLE_EDGE = [(-90, 1508), (-84, 1530), (-64, 1550), (-32, 1562), (0, 1566), (32, 1562), (64, 1550), (84, 1530), (90, 1508)]  # the dark sole band's upper edge, left to right
ARCH = [(-60, 1384), (-48, 1356), (-25, 1340), (0, 1336), (25, 1340), (48, 1356), (60, 1384)]  # the vamp's top edge inside the opening


def line(pts):
    return "[" + ", ".join(f"[{(x) / Wd:.4f}, {(y - y0) / Ln:.4f}]" for x, y in pts) + "]"


Path("ts/src/body-adult-loafer-data.ts").write_text(
    "// Generated by harness/risa_adult/loafer_trace.py from the loafer of ref/risa-adult/08-legs-closeup.png. Do not edit by hand.\n"
    "// The viewer's-left shoe, symmetrised about its own centre line; the right shoe is its mirror. [u, t]: u across in widths of the shoe from its centre line, t down in lengths of the shoe from the top of\n"
    "// its counters. The shoe is fitted to the foot in body-adult-garments.ts (loaferDetails), not placed by registration: Grok drew the legs of the uniform images shorter than this body's.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    f"/** The shoe's length over its width (277 px by 187). */\nexport const LOAFER_ASPECT = {Ln / Wd:.4f};\n\n"
    f"/** The silhouette, the notch at the top where the sock shows in it included. */\nexport const LOAFER_OUTLINE: Chain = {chain(outline)};\n\n"
    f"/** The dark sole band's upper edge, left to right; the band is everything below it inside the silhouette. */\nexport const LOAFER_SOLE_EDGE: readonly (readonly [number, number])[] = {line(SOLE_EDGE)};\n\n"
    f"/** The strap's top and bottom edges, left to right. */\nexport const LOAFER_STRAP_TOP: readonly (readonly [number, number])[] = {line(STRAP_TOP)};\nexport const LOAFER_STRAP_BOT: readonly (readonly [number, number])[] = {line(STRAP_BOT)};\n\n"
    f"/** The slot in the strap, a closed thin shape. */\nexport const LOAFER_SLOT: readonly (readonly [number, number])[] = {line(SLOT)};\n\n"
    f"/** The seam round the oval below the strap, left to right round the front. */\nexport const LOAFER_SEAM: readonly (readonly [number, number])[] = {line(SEAM)};\n\n"
    f"/** The vamp's top edge, inside the shoe's opening. */\nexport const LOAFER_ARCH: readonly (readonly [number, number])[] = {line(ARCH)};\n"
)
print("wrote ts/src/body-adult-loafer-data.ts")
