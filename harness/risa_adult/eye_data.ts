// Writes ts/src/body-adult-risa-eye-data.ts from out/risa_adult/eye.json (eye_trace.py): Risa's eye in the adult eye model's frame (docs/risa-polish-plan.md, stage 7).
//
//   node harness/risa_adult/eye_data.ts
//
// The outlines are thinned to every third point (they are drawn as straight runs between them, at the eye's scale a fraction of a canvas unit apart). The lower line is the part of the
// opening's outline below the iris centre (y over 4), from its outer end round to its inner end. The iris's middle band and its crescent are given against the eye colour as the preset takes
// it (#78925a, the reference's lower half, near the crescent), not against the trace's middle band: their value factors are scaled by the two values' ratio.

import { readFileSync, writeFileSync } from "node:fs";
import { hexToRgb01 } from "../../ts/src/colorutil.ts";

type P = [number, number];
const e = JSON.parse(readFileSync("out/risa_adult/eye.json", "utf8"));
const r2 = (x: number): string => (Math.round(x * 100) / 100).toFixed(2);
const pts = (a: readonly P[]): string => `[${a.map((q) => `[${r2(q[0])}, ${r2(q[1])}]`).join(", ")}]`;
const thin = (a: readonly P[]): P[] => a.filter((_, i) => i % 3 === 0);

// the lower line: the opening's outline points below y 4, as one run (the outline is closed, so the run may wrap round its start)
const ap: P[] = e.aperture;
const below = ap.map(([, y]) => y > 4);
const start = below.findIndex((b, i) => b && !below[(i - 1 + ap.length) % ap.length]);
const lower: P[] = [];
for (let k = 0; k < ap.length; k++) {
  const i = (start + k) % ap.length;
  if (!below[i]) break;
  lower.push(ap[i] as P);
}
// outer end first (x outward positive)
if ((lower[0] as P)[0] < (lower[lower.length - 1] as P)[0]) lower.reverse();

const preset = Math.max(...hexToRgb01("#78925a"));
const mid = Math.max(...(e.tones.mid_rgb as number[])) / 255;
const low = { dh: e.tones.low.dh, s: e.tones.low.s, v: (e.tones.low.v * mid) / preset };
// the iris's middle band against the same eye colour: darker (the preset's colour is the reference's lower half, near the crescent)
const body = { v: mid / preset };

writeFileSync(
  "ts/src/body-adult-risa-eye-data.ts",
  `// Generated by harness/risa_adult/eye_data.ts from harness/risa_adult/eye_trace.py (ref/risa-adult/00-bikini.png, both eyes levelled and averaged). Do not edit by hand.\n` +
    `// The adult eye model's frame: reference pixels about the iris centre, x outward (away from the nose), y down; the highlights in image orientation (the light from the viewer's upper left).\n\n` +
    `import type { AdultEyeShape } from "./body-adult-cuts.ts";\n\n` +
    `export const RISA_EYE: AdultEyeShape = {\n` +
    `  lid: ${pts(thin(e.lid))},\n` +
    `  aperture: ${pts(thin(e.aperture))},\n` +
    `  lower: ${pts(thin(lower))},\n` +
    `  iris: { c: [${r2(e.iris.c[0])}, ${r2(e.iris.c[1])}], rx: ${r2(e.iris.rx)}, ry: ${r2(e.iris.ry)} },\n` +
    `  body: { v: ${body.v.toFixed(3)} },\n` +
    `  crescentFrom: ${r2(e.iris_light_from)},\n` +
    `  crescent: { dh: ${low.dh.toFixed(4)}, s: ${low.s.toFixed(3)}, v: ${low.v.toFixed(3)} },\n` +
    `  pupil: { c: [${r2(e.pupil.c[0])}, ${r2(e.pupil.c[1])}], rx: ${r2(e.pupil.rx)}, ry: ${r2(e.pupil.ry)} },\n` +
    `  highlights: [${e.highlights.map((h: any) => `{ c: [${r2(h.c[0])}, ${r2(h.c[1])}], rx: ${r2(h.rx)}, ry: ${r2(h.ry)} }`).join(", ")}],\n` +
    `};\n`,
);
console.log(`wrote ts/src/body-adult-risa-eye-data.ts: lid ${thin(e.lid).length}, aperture ${thin(e.aperture).length}, lower ${thin(lower).length} points; crescent v ${low.v.toFixed(3)}`);
