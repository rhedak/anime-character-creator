// Writes ts/src/body-adult-risa-locks-data.ts from out/risa_adult/locks.json (locks_trace.py): Risa's front locks in the adult body's knot space (docs/risa-polish-plan.md, stage 4).
//
//   node harness/risa_adult/locks_data.ts
//
// The trace gives the locks as they are drawn on her slender build. `place` warps a knot before it maps it, so the stored knot is the one the build's warp takes to the traced position:
// found by halving, since the warp only rises (adult-build.test.ts pins that), the depth first, then the half-width at that depth. Drawn on another build, the locks follow its body.

import { readFileSync, writeFileSync } from "node:fs";
import { ADULT_BUILDS, type AdultBuild, warpDepth, warpHalf } from "../../ts/src/body-adult-build.ts";

type P = [number, number];
const b = ADULT_BUILDS["slender"] as AdultBuild;
const solve = (f: (x: number) => number, want: number, lo: number, hi: number): number => {
  for (let k = 0; k < 60; k++) {
    const mid = (lo + hi) / 2;
    if (f(mid) < want) lo = mid;
    else hi = mid;
  }
  return (lo + hi) / 2;
};
const knot = ([v, d]: P): P => {
  const td = solve((x) => warpDepth(b, x, v), d, -0.5, 6);
  const tv = solve((x) => warpHalf(b, td, x), Math.abs(v), 0, 3);
  return [Math.sign(v) * tv, td];
};
const r4 = (x: number): string => (Math.round(x * 10000) / 10000).toFixed(4);
const pts = (a: readonly P[]): string => `[${a.map((q) => `[${r4(q[0])}, ${r4(q[1])}]`).join(", ")}]`;
// every third point, and always the tip and the two ends: the outline is smoothed when drawn
const thin = (a: readonly P[], keep: readonly number[] = []): P[] => a.filter((_, i) => i % 3 === 0 || i === a.length - 1 || keep.includes(i));

const { locks } = JSON.parse(readFileSync("out/risa_adult/locks.json", "utf8")) as { locks: { outline: P[]; strands: P[][] }[] };
const body = locks
  .map((l) => {
    const tip = l.outline.reduce((best, q, i) => (q[1] > (l.outline[best] as P)[1] ? i : best), 0);
    return `  {\n    outline: ${pts(thin(l.outline, [tip]).map(knot))},\n    strands: [${l.strands.map((s) => pts(thin(s).map(knot))).join(", ")}],\n  },`;
  })
  .join("\n");
writeFileSync(
  "ts/src/body-adult-risa-locks-data.ts",
  `// Generated by harness/risa_adult/locks_data.ts from harness/risa_adult/locks_trace.py (the hair over the uniform in ref/risa-adult/01-school-uniform.png). Do not edit by hand.\n` +
    `// Risa's front locks (docs/risa-polish-plan.md, stage 4), in the adult body's knot space: [v, d] in head heights, v signed (the viewer's left negative), d below the chin, as \`place\` takes them.\n` +
    `// Each lock's outline runs down one edge to the tip and back up the other (its top, beside the neck, is not inked); its strands are lines inside it, top down.\n\n` +
    `import type { FrontLock } from "./body-adult-cuts.ts";\n\n` +
    `export const RISA_FRONT_LOCKS: readonly FrontLock[] = [\n${body}\n];\n`,
);
console.log(`wrote ts/src/body-adult-risa-locks-data.ts: ${locks.length} locks`);
