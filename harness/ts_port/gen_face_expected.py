"""Python's answers for the parts-face branches the corpus never reaches (`_eye_lash` without a `reach`, `_jaw_track`'s
default of 90 degrees, `_ear_place`, `_mouth_depth_share` and `_blush` over their range, a negative `beard_length`).

    PY harness/ts_port/gen_face_expected.py            writes ts/test/face-expected.ts

Whole floats are written with `repr`, which round-trips; the test compares bit for bit.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import _bootstrap  # noqa: F401
import anime_character_creator.character as ch  # noqa: E402

_bootstrap.assert_package_location()

OUT = Path(__file__).resolve().parents[2] / "ts" / "test" / "face-expected.ts"


def main() -> None:
    if OUT.exists() and "--force" not in sys.argv:
        raise SystemExit(f"{OUT} exists; pass --force to overwrite")
    faces = [
        {},
        {"lash": 0.3, "eye_tilt": -0.2, "eye_width": 1.1},
        {"lash": 2.0, "eye_corner": 1.2, "eye_openness": 0.6},
    ]
    lash = []
    for kw in faces:
        f = ch.FaceStyle(**kw)
        for reach in (None, 0.0, 3.0, 100.0):
            lash.append({"er": 12.5, "face": kw, "edge_w": 1.3, "reach": reach, "out": ch._eye_lash(12.5, f, 1.3, reach)})
    jaw = [
        {"y0": y0, "build": b, "drop": d, "inset": 0.9, "out": ch._jaw_track(y0, b, d, 0.9)}
        for y0, b, d in ((5.0, 0.5, 0.1), (-0.9, 0.0, 0.0), (0.63, 1.0, 0.2), (0.63, 0.1, -0.5))
    ]
    place = []
    for b in (0.0, 0.1, 0.5, 1.0):
        fn = ch._ear_place(b)
        for pt in ((0.0, 0.0), (0.5, 0.5), (1.0, 1.0), (0.2, 0.9)):
            place.append({"build": b, "pt": list(pt), "out": fn(pt)})
    depth = [{"x": x, "out": ch._mouth_depth_share(x)} for x in (0.0, 0.3, 0.85, 0.8500001, 0.9, 3.0, -1.0)]
    blush = [{"skin": s, "out": ch._blush(s)} for s in ("#000000", "#331a0d", "#7a5a40", "#b08060", "#d8b090", "#ffffff", "#f2c9a8")]
    # Whole parts on parameters the corpus does not name: a negative beard, extreme looks, a closed eye with a scar.
    wholes = []
    for kw, fkw in (
        ({"beard_color": "#5a3a1a", "beard_length": -0.3}, {}),
        ({"finish": "soft"}, {"mouth_open": 3.0, "scar_side": -2.0, "gaze": -2.0, "iris_aspect": 1.4, "lid_shadow": 0.3, "blush": 0.2}),
        ({"finish": "soft", "skin_tone": "#3a2418"}, {"eyes_closed": True, "nose_dot": True, "scar_side": 1}),
        ({"face_age": 3.0}, {"glasses": True, "brows_over_hair": True, "eye_gap": 0.2, "mouth_open": 0.5}),
    ):
        p = ch.CharacterParams(face=ch.FaceStyle(**fkw), **kw)
        sk = ch.skeleton_for(p)
        wholes.append(
            {"params": kw, "face": fkw, "out": {n: getattr(ch, "_" + n)(sk, p) for n in ("head", "face", "beard", "glasses", "ears")}}
        )
    data = {"wholes": wholes, "lash": lash, "jaw": jaw, "place": place, "depth": depth, "blush": blush}
    OUT.write_text(
        "// Generated by harness/ts_port/gen_face_expected.py: Python's answers where the corpus never goes.\n\n"
        f"export const FACE_EXPECTED = {json.dumps(data)} as const;\n"
    )
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
