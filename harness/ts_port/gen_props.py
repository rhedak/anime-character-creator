"""Emit the props domain's traced tables (and its scalar constants) as TypeScript, so coordinates are never typed by hand.

    PY harness/ts_port/gen_props.py [--force]      writes ts/src/props-tables.ts

Every module-level literal named in NAMES is read from the live Python module, so the numbers are Python's own, and the
`#` comment block directly above its assignment is copied above it. The output is then owned by hand; running this again
overwrites it, so it refuses unless `--force` is given. `_HAT_UNDERSIDE` and `_HAT_BRIM` are already in `tables.ts`;
`_KOU_MOUTH` is computed, so it is computed in `props.ts` by the ported code.
"""

