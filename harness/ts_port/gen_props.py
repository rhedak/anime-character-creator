def lit(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        r = repr(v)
        return r[:-2] if r.endswith(".0") else r
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (tuple, list)):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    raise TypeError(type(v))


def is_point(v: object) -> bool:
    return isinstance(v, tuple) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v)


def is_chain(v: object) -> bool:
    return (
        isinstance(v, tuple)
        and len(v) == 2
        and is_point(v[0])
        and isinstance(v[1], list)
        and all(isinstance(s, tuple) and len(s) == 2 and is_point(s[0]) and is_point(s[1]) for s in v[1])
    )


def ts_type(v: object) -> str:
    if isinstance(v, str):
        return "string"
    if isinstance(v, (int, float)):
        return "number"
    if is_point(v):
        return "Point"
    if is_chain(v):
        return "Chain"
    if isinstance(v, list) and all(is_chain(x) for x in v):
        return "readonly Chain[]"
    raise TypeError(v)


def emit(v: object, ty: str) -> list[str]:
    """One segment per line for the long tables."""
    if ty == "Chain":
        start, segs = v  # type: ignore[misc]
        out = [f"  {lit(start)},", "  ["]
        out += [f"    {lit(s)}," for s in segs]
        out += ["  ],"]
        return ["["] + out + ["]"]
    if ty == "readonly Chain[]":
        out = ["["]
        for chain in v:  # type: ignore[attr-defined]
            inner = emit(chain, "Chain")
            out += ["  " + inner[0]] + ["  " + x for x in inner[1:-1]] + ["  " + inner[-1] + ","]
        out.append("]")
        return out
    return [lit(v)]


def comment_above(lines: list[str], lineno: int) -> list[str]:
    """The contiguous `#` lines directly above the 1-based `lineno`."""
    i = lineno - 2
    block: list[str] = []
    while i >= 0 and lines[i].lstrip().startswith("#"):
        block.append(lines[i].strip())
        i -= 1
    return ["//" + c[1:] if len(c) > 1 else "//" for c in reversed(block)]


def main() -> None:
    if OUT.exists() and "--force" not in sys.argv:
        raise SystemExit(f"{OUT} exists and is hand-owned now; pass --force to overwrite")
    text = SRC.read_text()
    lines = text.splitlines()
    tree = ast.parse(text)
    where: dict[str, int] = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            where[node.target.id] = node.lineno
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            where[node.targets[0].id] = node.lineno
    out = [
        "// The props domain's traced tables and constants. Generated by harness/ts_port/gen_props.py from the Python,",
        "// with each constant's comment copied from above it, then owned by hand. Names are Python's without the underscore.",
        "",
        'import type { Chain, Point } from "./tables.ts";',
        "",
    ]
    for name in NAMES:
        v = getattr(ch, name)
        ty = ts_type(v)
        out += comment_above(lines, where[name])
        body = emit(v, ty)
        out.append(f"export const {name.lstrip('_')}: {ty} = {body[0]}")
        out += body[1:]
        if len(body) > 1:
            out[-1] += ";"
        else:
            out[-1] += ";"
        out.append("")
    OUT.write_text("\n".join(out))
    print("wrote", OUT, OUT.stat().st_size, "bytes", len(NAMES), "names")


if __name__ == "__main__":
    main()
