"""Assign every top-level name of character.py to a TypeScript module, from who needs it.

    PY harness/ts_port/modules.py            writes harness/ts_port/modules.json and docs/ts-port-modules.md

A root is a function `render_character` calls. Its closure is everything it reaches (functions, classes, module-level
constants). A name's OWNERS are the domains of the roots that reach it. If X calls Y then Y's owners contain X's, so the
assignment below has no circular dependency between modules:

    one domain owns it            -> parts-<domain>  (hair, face, body, arms, garments, props)
    owners all within face/hair/props, two or more  -> core-head
    owners all within arms/body/garments/props, two or more -> core-limbs
    anything else (spans both groups)               -> core-common

core-common depends on nothing; core-head and core-limbs depend on core-common only; a domain module depends on its
core module(s) and core-common.
"""

from __future__ import annotations

import ast
import collections
import json
from pathlib import Path

import _bootstrap  # noqa: F401

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "anime_character_creator" / "character.py"

DOM = {
    "hair": "_hair_defs _hair_tail _hair_lines _hair_mass _hair_front _hair_knot _hair_tie _hair_clip _brows_over_hair".split(),
    "face": "_head _face _ears _beard _glasses _goggles_strap _goggles _blindfold _mask _neck".split(),
    "body": "_torso _without_raised_sleeves _legs_and_boots _underskirt _skirt _hakama _hanging_sleeves _navel _underwear_top _chest_lines _bust_lines _bust_over_arms".split(),
    "arms": "_arms _hands_after_coat".split(),
    "garments": "_tunic _robe_front _placket _chest_pockets _strap _apron _coat _pouches _crystal_harness _traced_coat_and_belt _belt _collar _shoulder_bars _ribbon".split(),
    "props": "_katana _staff _familiar _hat_underside _hat _headscarf".split(),
}
HEAD = {"face", "hair", "props"}
LIMBS = {"arms", "body", "garments", "props"}


def main() -> None:
    src = SRC.read_text()
    tree = ast.parse(src)
    defs = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    assigns: dict[str, ast.AST] = {}
    for n in tree.body:
        if isinstance(n, ast.Assign):
            for tg in n.targets:
                if isinstance(tg, ast.Name):
                    assigns[tg.id] = n
                if isinstance(tg, ast.Subscript) and isinstance(tg.value, ast.Name):
                    assigns.setdefault(tg.value.id, n)
        if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
            assigns[n.target.id] = n
    node_of = lambda k: defs.get(k) or assigns.get(k)  # noqa: E731
    names_in = lambda node: {x.id for x in ast.walk(node) if isinstance(x, ast.Name)}  # noqa: E731

    def closure(root: str) -> set[str]:
        seen: set[str] = set()
        todo = [root]
        while todo:
            k = todo.pop()
            if k in seen:
                continue
            seen.add(k)
            n = node_of(k)
            if n is None:
                continue
            for nm in names_in(n):
                if nm in defs or nm in assigns:
                    todo.append(nm)
        return seen

    root_dom = {r: d for d, rs in DOM.items() for r in rs}
    owners: dict[str, set[str]] = collections.defaultdict(set)
    for r, d in root_dom.items():
        for k in closure(r):
            owners[k].add(d)

    def module_of(o: set[str]) -> str:
        if len(o) == 1:
            return "parts-" + next(iter(o))
        if o <= HEAD:
            return "core-head"
        if o <= LIMBS:
            return "core-limbs"
        return "core-common"

    mods: dict[str, list[dict]] = collections.defaultdict(list)
    for k, o in owners.items():
        n = node_of(k)
        if n is None:
            continue
        kind = "class" if isinstance(n, ast.ClassDef) else "def" if isinstance(n, ast.FunctionDef) else "const"
        mods[module_of(o)].append({"name": k, "kind": kind, "line": n.lineno, "end": n.end_lineno, "lines": n.end_lineno - n.lineno + 1, "owners": sorted(o)})
    for v in mods.values():
        v.sort(key=lambda e: e["line"])
    # the roots themselves are in their domain module
    out = {m: {"lines": sum(e["lines"] for e in v), "functions": sum(e["kind"] == "def" for e in v), "names": v} for m, v in sorted(mods.items())}
    (ROOT / "harness/ts_port/modules.json").write_text(json.dumps(out, indent=1))

    md = ["# The Phase 4 modules", "", "Generated by `harness/ts_port/modules.py` from the call graph of `character.py`. Dependencies run one way:",
          "`core-common` needs nothing; `core-head` and `core-limbs` need `core-common`; a `parts-*` module needs its core module(s) and `core-common`.", "",
          "| Module | Names | Functions | Lines | Depends on |", "| --- | --- | --- | --- | --- |"]
    dep = {"core-common": "(none)", "core-head": "core-common", "core-limbs": "core-common"}
    for m, v in out.items():
        d = dep.get(m) or ("core-common" + (", core-head" if m in ("parts-hair", "parts-face") else "") + (", core-limbs" if m in ("parts-body", "parts-arms", "parts-garments") else "") + (", core-head, core-limbs" if m == "parts-props" else ""))
        md.append(f"| `{m}` | {len(v['names'])} | {v['functions']} | {v['lines']} | {d} |")
    md += ["", "A name's lines are its own definition only (a data table counts as lines). Per-module name lists with Python line numbers are in `harness/ts_port/modules.json`.", ""]
    (ROOT / "docs/ts-port-modules.md").write_text("\n".join(md))
    for m, v in out.items():
        print(f"{m:14s} {len(v['names']):4d} names {v['functions']:4d} fns {v['lines']:6d} lines")


if __name__ == "__main__":
    main()
