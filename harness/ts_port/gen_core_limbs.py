"""Emit core-limbs' coordinate tables as TypeScript literals, so coordinates are never typed by hand.

    PY harness/ts_port/gen_core_limbs.py            writes ts/src/core-limbs-tables.ts
    PY harness/ts_port/gen_core_limbs.py --expected writes ts/test/core-limbs-expected.ts

The first file is a first draft that is then owned by hand: once it is in `ts/src/`, edit it there. Running this again
overwrites the file, so it refuses unless `--force` is given. The second file (the `--expected` mode) holds what Python's
import-time code computed (`_HAND_FIST`, `_HAND_OPEN`), for a test that the TypeScript code, which builds them at import time
by the ported functions, arrives at the same numbers.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

import _bootstrap  # noqa: F401

import anime_character_creator.character as ch  # noqa: E402

_bootstrap.assert_package_location()

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "ts" / "src" / "core-limbs-tables.ts"
EXPECTED = ROOT / "ts" / "test" / "core-limbs-expected.ts"

# name in TS, python attribute, TS type, one line of why
CHAINS = [
    ("LAB_COAT_PANEL_LEFT", "_LAB_COAT_PANEL_LEFT", "Chain", "Keiko's lab coat: the left front panel, from the measured profile."),
    ("LAB_COAT_PANEL_RIGHT", "_LAB_COAT_PANEL_RIGHT", "Chain", "Keiko's lab coat: the right front panel."),
    ("LAB_COAT_LAPEL_LEFT", "_LAB_COAT_LAPEL_LEFT", "Chain", "Keiko's lab coat: the left lapel, traced."),
    ("LAB_COAT_LAPEL_RIGHT", "_LAB_COAT_LAPEL_RIGHT", "Chain", "Keiko's lab coat: the right lapel, traced."),
]
CHAIN_NAMES = {id(getattr(ch, attr)): name for name, attr, _t, _w in CHAINS}


def lit(v: object, named: bool = True) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        r = repr(v)
        return r[:-2] if r.endswith(".0") else r
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if v is None:
        return "null"
    if named and id(v) in CHAIN_NAMES:
        return CHAIN_NAMES[id(v)]
    if isinstance(v, (tuple, list)):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    raise TypeError(type(v))


def fields_literal(obj: object, only_non_default: bool) -> str:
    parts = []
    for f in dataclasses.fields(obj):  # type: ignore[arg-type]
        value = getattr(obj, f.name)
        if only_non_default and f.default is not dataclasses.MISSING and value == f.default:
            continue
        parts.append(f"{f.name}: {lit(value)}")
    return "{ " + ", ".join(parts) + " }"


def main() -> None:
    if "--expected" in sys.argv:
        lines = [
            "// Generated by harness/ts_port/gen_core_limbs.py --expected from what Python's import-time code computed.",
            "// The numbers `_fist()` and `_square_wrist()` give, for the test that the ported code builds the same ones.",
            "",
            'import type { Chain } from "../src/tables.ts";',
            "",
            f"export const HAND_FIST: readonly (readonly [Chain, readonly Chain[], readonly Chain[]])[] = {lit(ch._HAND_FIST)};",
            "",
            f"export const HAND_OPEN: readonly (readonly [Chain, readonly Chain[], readonly Chain[]])[] = {lit(ch._HAND_OPEN)};",
            "",
        ]
        EXPECTED.write_text("\n".join(lines))
        print("wrote", EXPECTED, EXPECTED.stat().st_size, "bytes")
        return
    if OUT.exists() and "--force" not in sys.argv:
        raise SystemExit(f"{OUT} exists and is hand-owned now; pass --force to overwrite")
    lines = [
        "// Generated once by harness/ts_port/gen_core_limbs.py from the Python tables, then owned by hand.",
        "// The traced garment and sleeve cuts and the traced hand: coordinates in head radii, as the trace tools wrote them.",
        "",
        'import type { Chain, Point } from "./tables.ts";',
        "",
        "/** A traced garment: closed shapes to fill and open lines to stroke (the Python `GarmentCut`; see `core-limbs.ts`). */",
        "export interface GarmentCut {",
        "  readonly fills: readonly Chain[];",
        "  readonly lines: readonly Chain[];",
        "  readonly over_arms: boolean;",
        "  readonly bust_line_after: number | null;",
        "  readonly ref_body: string;",
        "  readonly per_leg: boolean;",
        "  readonly shades: readonly (number | null)[];",
        "  readonly holes: readonly (readonly [number, Chain])[];",
        "  readonly line_weight: number;",
        "  readonly arm_lines: readonly [number, number] | null;",
        "  readonly sleeve_hem_y: number | null;",
        "  readonly shoulder_y: number | null;",
        "  readonly hem_corners: readonly [Point, Point] | null;",
        "}",
        "",
        "/** A traced sleeve and its cuff (the Python `SleeveCut`). */",
        "export interface SleeveCut {",
        "  readonly pivot: Point;",
        "  readonly wrist: Point;",
        "  readonly half_w: number;",
        "  readonly sleeve: Chain;",
        "  readonly cuff: Chain;",
        "}",
        "",
        "/** One piece of a traced hand: its outline, its holes and its interior lines. */",
        "export type HandPiece = readonly [Chain, readonly Chain[], readonly Chain[]];",
        "",
        "/** The Python dataclass defaults of `GarmentCut`, so a cut names only what differs. */",
        "const GARMENT_CUT_DEFAULTS = {",
    ]
    defaults = {f.name: f.default for f in dataclasses.fields(ch.GarmentCut)}
    for name, value in defaults.items():
        if value is dataclasses.MISSING:
            continue
        lines.append(f"  {name}: {lit(value)},")
    lines += [
        "} as const;",
        "",
        "/** `GarmentCut(fills=..., ...)`: the fields named, the rest at their defaults. */",
        "export const garmentCut = (given: Partial<GarmentCut> & Pick<GarmentCut, \"fills\">): GarmentCut => ({",
        "  ...GARMENT_CUT_DEFAULTS,",
        "  ...given,",
        "});",
        "",
    ]
    for ts_name, attr, ty, why in CHAINS:
        lines.append(f"/** {why} */")
        lines.append(f"export const {ts_name}: {ty} = {lit(getattr(ch, attr), named=False)};")
        lines.append("")
    lines.append("/** The coat cuts by name (`COAT_CUTS`): the traced coats a `Outfit.coat_cut` names. */")
    lines.append("export const COAT_CUTS: Readonly<Record<string, GarmentCut>> = {")
    for key, cut in ch.COAT_CUTS.items():
        if key == "blazer":
            lines.append("  // Python adds this one further down the file, `COAT_CUTS[\"blazer\"] = GarmentCut(...)` (character.py:9688).")
        lines.append(f"  {key}: garmentCut({fields_literal(cut, True)}),")
    lines.append("};")
    lines.append("")
    lines.append("/** The traced sleeves by name (`SLEEVE_CUTS`): what an `Outfit.sleeve_cut` names. */")
    lines.append("export const SLEEVE_CUTS: Readonly<Record<string, SleeveCut>> = {")
    for key, cut in ch.SLEEVE_CUTS.items():
        lines.append(f"  {key}: {fields_literal(cut, False)},")
    lines.append("};")
    lines.append("")
    lines.append("/** The traced relaxed hand's pieces in drawing order: outline, holes, interior lines (`_HAND_RELAXED`). */")
    lines.append(f"export const HAND_RELAXED: readonly HandPiece[] = {lit(ch._HAND_RELAXED)};")
    lines.append("")
    lines.append("/** The direction the reference's forearm ran into the relaxed hand, wrist to hand. */")
    lines.append(f"export const HAND_RELAXED_INTO: Point = {lit(ch._HAND_RELAXED_INTO)};")
    lines.append("")
    lines.append("/** The direction the fist's forearm runs into it, wrist to hand: the traced grip's, fingers toward -x. */")
    lines.append(f"export const HAND_FIST_INTO: Point = {lit(ch._HAND_FIST_INTO)};")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
