"""Fit the agreed bust contour (bust_overlay.py) into the body's own units and emit ts/src/body-adult-bust-data.ts.

    ./harness/run.sh harness/franzi/bust_fit.py

One breast (the viewer's left), a closed chain of [x, d] points: x in head heights from the body's centre line (negative to the
left), d in head heights below the chin, the same units as body-adult-top-data.ts. The other is its mirror, made in the drawing.
The contour is a line (the breast's edge), not an ink edge, so there is no stroke inset. Outlines only: nothing is drawn inside.
"""

import sys
from pathlib import Path

sys.path.insert(0, "/Users/henrik/git/anime-character-creator/.claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402
from bust_overlay import INFERRED, VISIBLE, catmull  # noqa: E402

CX, CHIN, H = 668.2, 434.0, 352.0
# the loop: round the outside and underside to the centre, then up the inner edge to where it began
loop = catmull(INFERRED) + catmull(VISIBLE[::-1])[1:]
pts = [((440 + x / 2 - CX) / H, (440 + y / 2 - CHIN) / H) for x, y in loop]
start, segs = tl.fit_closed(pts, 0.003)
xs = [p[0] for p in pts]; ds = [p[1] for p in pts]
print("breast extent x", round(min(xs), 3), round(max(xs), 3), "d", round(min(ds), 3), round(max(ds), 3), "segments", len(segs))


def pt(p):
    return f"[{p[0]:.4f}, {p[1]:.4f}]"


body = ", ".join(f"[{pt(c)}, {pt(e)}]" for c, e in segs)
Path("ts/src/body-adult-bust-data.ts").write_text(
    "// Generated by harness/franzi/bust_fit.py from the contour agreed with the owner over ref 04 (bust_overlay.py). Do not edit.\n"
    "// The viewer's-left breast's edge, closed; points are [x, d] in head heights (x from the centre line, d below the chin).\n"
    "// An outline only. The right breast is this one mirrored.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    f"export const ADULT_BREAST: Chain = [{pt(start)}, [{body}]];\n"
)
print("wrote ts/src/body-adult-bust-data.ts")
