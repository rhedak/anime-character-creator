"""Measure each eye's black lid in ref 04, column by column, into per-eye tables for ts/src/body-adult-lid-data.ts.

    ./harness/run.sh harness/franzi/lid_measure.py

The first lid was one pair of circles drawn for the viewer's-left eye and mirrored onto the right (the owner: the eyelashes and the lid do not attach on the right eye).
Overlaid on the reference (harness/franzi/eye_outline.py) it was about 3 px high on the left eye, and on the right eye its inner end ended well away from the reference's long thin
tail, so a lash drawn on the tail did not touch it. The two eyes differ (the head turns a little), so each is measured on its own.

Eye frame as in body-adult-eyes.ts: origin at the iris centre (left eye (606, 325), right eye (718.5, 321.5) on ref 04), x positive outward (away from the nose), y down.
For each frame x from X_TIP to X_OUT, in steps of 1: the lid's top edge is where the lightness first falls through 110 coming down the column (sub-pixel, linear), and its bottom edge
where it rises back through 40 below the black (the iris top is dark brown, down to lightness 45 or so under the lid, so 55 let the lid run on into it and gave a 12 px lid). Columns where no black run starts within
the lid window, or where the run joins hair or the iris outline (thickness over 16 px), are skipped and filled by interpolation. Then smoothed over 5 columns.
Writes out/franzi/lid_tables.json and ts/src/body-adult-lid-data.ts: LID_L and LID_R, arrays of [x, top, bottom].
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

a = np.array(Image.open("ref/franzi/04-bikini-fullbody.png").convert("RGBA")).astype(float)
lum = a[..., :3].mean(2)
EYES = {-1: ("L", 606.0, 325.0), 1: ("R", 718.5, 321.5)}
X_TIP, X_OUT = {-1: -22, 1: -24}, {-1: 22, 1: 26}  # the right eye's lid runs on into a long thin tail, steep past x = -24, which a column measure cannot follow (the tail is a lash stroke)


def column_edges(rx, iy, lo, hi):
    """Top and bottom of the lid's black run in reference column rx, searching rows iy+lo to iy+hi, as sub-pixel rows relative to iy, or None."""
    ys = np.arange(iy + lo, iy + hi, 0.25)
    col = ndimage.map_coordinates(lum, [ys, np.full(len(ys), float(rx))], order=1)
    dark = col < 40
    if not dark.any():
        return None
    i = int(np.argmax(dark))
    j = i
    while j + 1 < len(dark) and dark[j + 1]:
        j += 1
    while i > 0 and col[i - 1] < 110:
        i -= 1
    k = j
    while k + 1 < len(col) and col[k + 1] < 40:
        k += 1
    return ys[i] - iy, ys[k] - iy


tables = {}
for side, (name, ix, iy) in EYES.items():
    xs = np.arange(X_TIP[side], X_OUT[side] + 1)
    # the lid is followed from the middle outward and inward: each column's search window sits around the previous column's top edge, so a hair strand or the crease
    # (both dark, both near) is not mistaken for it
    start = {-1: -29.0, 1: -32.5}[side]
    found = {}
    for direction in (1, -1):
        prev = start
        for x in (xs[xs >= 0] if direction == 1 else xs[xs < 0][::-1]):
            e = column_edges(ix + side * x, iy, prev - 5, prev + 20)
            if e is None or e[1] - e[0] > 14 or abs(e[0] - prev) > 4.5:
                continue
            found[x] = e
            prev = e[0]
    rows = [(x, *found[x]) if x in found else (x, np.nan, np.nan) for x in xs]
    arr = np.array(rows, float)
    ok = ~np.isnan(arr[:, 1])
    for c in (1, 2):
        arr[:, c] = np.interp(arr[:, 0], arr[ok, 0], arr[ok, c])
        arr[:, c] = ndimage.gaussian_filter1d(arr[:, c], 1.6 if c == 1 else 3.2, mode="nearest")  # the bottom edge runs along the iris and its highlight and is noisier
    tables[name] = arr
    print(f"eye {name}: columns measured {int(ok.sum())} of {len(xs)}; sample (x, top, bottom, thickness):")
    for x in (-24, -20, -16, -12, -8, 0, 8, 14, 20):
        if X_TIP[side] <= x <= X_OUT[side]:
            r = arr[arr[:, 0] == x][0]
            print(f"   x {x:+3d}: top {r[1]:+6.1f}  bottom {r[2]:+6.1f}  thick {r[2] - r[1]:4.1f}")
json.dump({k: v.tolist() for k, v in tables.items()}, open("out/franzi/lid_tables.json", "w"))


def rows_ts(arr):
    return ", ".join(f"[{x:.0f}, {t:.2f}, {b:.2f}]" for x, t, b in arr)


Path("ts/src/body-adult-lid-data.ts").write_text(
    "// Generated by harness/franzi/lid_measure.py from ref/franzi/ 04. Do not edit by hand.\n"
    "// Each eye's black lid, measured column by column in its own frame (origin at the iris centre, x outward, y down, reference pixels): [x, top edge, bottom edge].\n\n"
    f"export const LID_L: readonly (readonly [number, number, number])[] = [{rows_ts(tables['L'])}];\n\n"
    f"export const LID_R: readonly (readonly [number, number, number])[] = [{rows_ts(tables['R'])}];\n"
)
print("wrote ts/src/body-adult-lid-data.ts")
