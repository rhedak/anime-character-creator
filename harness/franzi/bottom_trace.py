"""Trace the briefs of ref 04 (the segment layer white-bikini-bottom.png) into a chain for ts/src/body-adult-bottom-data.ts.

    PYTHONPATH=.claude/skills/trace-reference ./harness/run.sh harness/franzi/bottom_trace.py

Same method as top_trace.py. Coordinates are the body's own: depth d in head heights below the chin (row 434 of the reference canvas is d = 0, a
head height is 352 px) and x in head heights from the garment's own centre line (its two edges are 357 px apart and centred on column 664.4, not on the
body's 668.2: the reference figure leans a few px), so `place()` in body-adult-parts.ts maps them onto the skeleton as it does the top. The mask is eroded
3 px so the traced line sits on the centre of our stroke, smoothed (a lower threshold than 0.5 keeps the wings' convex tips), and made symmetric by averaging
the two halves about that centre line. The old briefs were a band from a made-up waist line with a straight top and a guessed leg curve: the reference's
waistband curves down to the centre, its wings flare to the hips and its leg openings run in long diagonals to a flat gusset (the owner: a completely different
shape). Writes out/franzi/bottom.json and ts/src/body-adult-bottom-data.ts.
"""

import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

sys.path.insert(0, ".claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402

OUT = Path("out/franzi")
CHIN, H = 434.0, 352.0
mask = np.array(Image.open("ref/franzi/segments/04-bikini-fullbody/white-bikini-bottom.png"))[..., 3] > 128
mask = ndimage.binary_erosion(ndimage.binary_fill_holes(mask), iterations=3)
ys, xs = np.nonzero(mask)
# the garment's own centre line: the middle of its widest row's two edges, averaged over the rows where both wings exist
rows = [y for y in range(ys.min() + 8, ys.max() - 8) if mask[y].any()]
cs = [(np.nonzero(mask[y])[0].min() + np.nonzero(mask[y])[0].max()) / 2 for y in rows]
C = float(np.mean(cs))
print("garment centre column %.2f (rows %d to %d), spread of the row centres %.2f px" % (C, rows[0], rows[-1], np.std(cs)))
# symmetric: average the mask with its mirror image about C, smoothed, thresholded below one half so the convex tips stay
xx = np.arange(mask.shape[1])
src = np.clip(np.round(2 * C - xx).astype(int), 0, mask.shape[1] - 1)
mirror = mask[:, src]
sym = ndimage.gaussian_filter((mask.astype(float) + mirror.astype(float)) / 2, 2.5) > 0.40
np.save(OUT / "bottom_mask.npy", sym)
pts = [((x - C) / H, (y - CHIN) / H) for x, y in tl.boundary(sym)]  # (x in H, d in H)
start, segs = tl.fit_closed(pts, 0.004)
xs_ = [p[0] for p in pts]; ds_ = [p[1] for p in pts]
print("bottom extent x", round(min(xs_), 3), round(max(xs_), 3), "d", round(min(ds_), 3), round(max(ds_), 3), "segments", len(segs))
json.dump({"bottom": (start, segs), "centre": C}, open(OUT / "bottom.json", "w"), default=lambda o: list(o))


def pt(p):
    return f"[{p[0]:.4f}, {p[1]:.4f}]"


body = ", ".join(f"[{pt(c)}, {pt(e)}]" for c, e in segs)
Path("ts/src/body-adult-bottom-data.ts").write_text(
    "// Generated by harness/franzi/bottom_trace.py from the bikini-bottom layer of ref 04. Do not edit by hand.\n"
    "// Points are [x, d]: x in head heights from the garment's centre line, d in head heights below the chin; the outline is symmetric.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    f"export const ADULT_BOTTOM: Chain = [{pt(start)}, [{body}]];\n"
)
print("wrote ts/src/body-adult-bottom-data.ts")
