"""Trace Franzi's brows from ref 04 (dark pixels clear of the hair layer) into filled outlines in head radii.

    ./harness/run.sh harness/franzi/brow_trace.py

Per eye: the dark region in a box above the eye, minus the hair layer grown a few pixels, its upper and lower edge per column,
smoothed. Written as polygons [x, y] in head radii of the reference calibration (origin (660, 270.5), 175.7 px/radius) to
out/franzi/brows.json, with out/franzi/brow-trace.png (the polygons over the reference, 8x).
"""

import json

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

OX, OY, S = 660.0, 270.5, 175.7
a = np.array(Image.open("ref/franzi/04-bikini-fullbody.png").convert("RGBA")).astype(int)
lum = a[..., :3].mean(2)
hair = ndimage.binary_dilation(np.array(Image.open("ref/franzi/segments/04-bikini-fullbody/black-hair.png"))[..., 3] > 128, iterations=3)
dark = (lum < 95) & (a[..., 3] > 128) & ~hair
res = {}
for name, (x0, x1, y0, y1) in {"R": (684, 742, 254, 276), "L": (596, 640, 264, 286)}.items():
    m = np.zeros_like(dark)
    m[y0:y1, x0:x1] = dark[y0:y1, x0:x1]
    lab, n = ndimage.label(m)
    sizes = ndimage.sum(m, lab, range(1, n + 1))
    comp = lab == (1 + int(np.argmax(sizes)))
    up, lo = [], []
    for x in range(x0, x1):
        ys = np.nonzero(comp[:, x])[0]
        if len(ys):
            up.append((x, ys.min() - 0.5)), lo.append((x, ys.max() + 0.5))
    ux = np.array([p[0] for p in up], float)
    uy = ndimage.gaussian_filter1d(np.array([p[1] for p in up]), 1.5)
    ly = ndimage.gaussian_filter1d(np.array([p[1] for p in lo]), 1.5)
    poly = [(x, y) for x, y in zip(ux, uy)] + [(x, y) for x, y in zip(ux[::-1], ly[::-1])]
    res[name] = [[(x - OX) / S, (y - OY) / S] for x, y in poly]
    print(name, "columns", len(up), "x", ux.min(), ux.max(), "thickness mid", round(float((ly - uy)[len(uy) // 2]), 1), "px")
json.dump(res, open("out/franzi/brows.json", "w"))
Z = 8
im = Image.open("ref/franzi/04-bikini-fullbody.png").convert("RGBA")
bg = Image.new("RGBA", im.size, "white"); bg.alpha_composite(im)
for name, box in (("R", (680, 248, 790, 318)), ("L", (545, 250, 645, 320))):
    c = bg.convert("RGB").crop(box).resize(((box[2] - box[0]) * Z, (box[3] - box[1]) * Z), Image.LANCZOS)
    d = ImageDraw.Draw(c)
    pts = [((OX + x * S - box[0]) * Z, (OY + y * S - box[1]) * Z) for x, y in res[name]]
    d.line(pts + [pts[0]], fill=(255, 0, 0), width=2)
    c.save(f"out/franzi/brow-trace-{name}.png")

def pt(q):
    return f"[{q[0]:.4f}, {q[1]:.4f}]"


body = "\n".join(f"/** The brow on the viewer's {'right' if k == 'R' else 'left'}: a filled outline, traced from the dark pixels clear of the hair. */\nexport const ADULT_BROW_{k}: readonly (readonly [number, number])[] = [{', '.join(pt(q) for q in v)}];\n" for k, v in res.items())
open("ts/src/body-adult-brow-data.ts", "w").write("// Generated by harness/franzi/brow_trace.py from ref 04. Do not edit by hand. Points are [x, y] in head radii from the head centre.\n\n" + body)
print("wrote ts/src/body-adult-brow-data.ts")
