"""Measure the Franzi target's outline for the adult body: torso, arm and leg edges per row, in head heights.

    ./harness/run.sh harness/franzi/outline.py

Reads out/franzi/target.png (measure.py), writes out/franzi/outline.json and prints the knot tables that
ts/src/body-adult.ts carries. Each value is symmetrised (mean of the left and right edge about the body centre).
Depth d is in head heights below the chin (H = 352 px, the references' head height); x is in head heights from the
body centre line.
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image

OUT = Path("out/franzi")
H = 352.0
tm = np.array(Image.open(OUT / "target.png").convert("L")) > 128
top = int(np.where(tm.any(1))[0].min())
chin = top + H


def runs(row):
    d = np.diff(np.concatenate([[0], row.astype(int), [0]]))
    return list(zip(np.where(d == 1)[0], np.where(d == -1)[0]))


# Centre line: the midpoint of the outer extent at the pelvis rows.
cs = []
for d in (1.9, 2.0, 2.1):
    r = runs(tm[int(chin + d * H)])
    cs.append((r[0][0] + r[-1][1]) / 2)
cx = float(np.mean(cs))


def sym(a, b):
    return (abs(cx - a) + abs(b - cx)) / 2 / H


rows = {}
for i in range(0, 55):
    d = round(0.1 + i * 0.1, 2)
    y = int(chin + d * H)
    if y >= tm.shape[0] or not tm[y].any():
        break
    r = runs(tm[y])
    rows[d] = r

torso, arm, leg = [], [], []
for d, r in rows.items():
    n = len(r)
    outer = sym(r[0][0], r[-1][1])
    if n == 1 or (n == 2 and d < 0.9):
        torso.append((d, round(outer, 3)))  # merged: neck/shoulders/arms/torso
        continue
    if d >= 1.0 and n >= 3:
        # arms free of the torso: runs[0] and runs[-1] are arms (hands included further down)
        arm.append((d, round(sym(r[0][0], r[-1][1]), 3), round(sym(r[0][1], r[-1][0]), 3)))
    if n == 3:
        b = r[1]
        torso.append((d, round(sym(b[0], b[1]), 3)))
    elif n == 4 or (n == 2 and d >= 2.6):
        # legs: with arms/hands present the two middle runs, else the two runs
        lg = r[1:3] if n == 4 else r
        leg.append((d, round(sym(lg[0][0], lg[1][1]), 3), round(sym(lg[0][1], lg[1][0]), 3)))
print("centre x", cx, "chin row", chin)
print("merged/torso (d, half-width H):", torso)
print("arm (d, outer, inner) H:", arm)
print("legs (d, outer, inner) H:", leg)
(OUT / "outline.json").write_text(json.dumps({"torso": torso, "arm": arm, "leg": leg}))


# ---- the knot tables ts/src/body-adult-data.ts carries (smoothed with weights 1/4, 1/2, 1/4, endpoints kept) ----
def smooth(pts):
    out = [pts[0]]
    for i in range(1, len(pts) - 1):
        out.append((pts[i][0], round(0.25 * pts[i - 1][1] + 0.5 * pts[i][1] + 0.25 * pts[i + 1][1], 3)))
    out.append(pts[-1])
    return out


def pick(tab, col, lo, hi):
    return [(d, float(v[col - 1] if isinstance(v, tuple) else v)) for d, *v in tab if lo <= d <= hi]


arm_o = [(d, o) for d, o, i in arm if 1.1 <= d <= 2.6]
arm_i = [(d, i) for d, o, i in arm if 1.1 <= d <= 2.6]
torso_t = [(d, w) for d, w in torso if 1.1 <= d <= 2.2]
leg_o = [(d, o) for d, o, i in leg if 2.3 <= d <= 5.3]
leg_i = [(d, i) for d, o, i in leg if 2.3 <= d <= 5.3]
shoulder = [(0.3, 0.571), (0.4, 0.615), (0.5, 0.634), (0.6, 0.639), (0.7, 0.638), (0.8, 0.636), (0.9, 0.641)]


def ts(name, pts, doc):
    body = ", ".join(f"[{d:g}, {float(v):g}]" for d, v in pts)
    return f"/** {doc} */\nexport const {name}: readonly (readonly [number, number])[] = [{body}];\n"


tables = [
    ts("SHOULDER_OUTER", shoulder, "Shoulder and upper arm, outer edge, arms and torso merged: [depth, half-width]."),
    ts("ARM_OUTER", smooth(arm_o), "Arm and hand, outer edge, from the armpit down."),
    ts("ARM_INNER", smooth(arm_i), "Arm and hand, inner edge, from the armpit down."),
    ts("TORSO_SIDE", smooth(torso_t), "Torso side from under the arm to the hip."),
    ts("LEG_OUTER", smooth(leg_o), "Leg, outer edge, hip to sole."),
    ts("LEG_INNER", smooth(leg_i), "Leg, inner edge, crotch to sole."),
]
header = """// Generated by harness/franzi/outline.py from the fused Franzi target (out/franzi/target.png). Do not edit by hand.
// Depth is in head heights (H) below the chin, half-width in H from the body centre line; a head height is two head
// radii. Each edge is the left/right mean, smoothed 1/4, 1/2, 1/4. docs/adult-body-status.md has the measurement.

"""
Path("ts/src/body-adult-data.ts").write_text(header + "\n".join(tables))
print("wrote ts/src/body-adult-data.ts")
