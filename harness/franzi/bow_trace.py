"""The apron's bow, from ref 00, into ts/src/body-adult-bow-data.ts.

    ./harness/run.sh harness/franzi/bow_trace.py

The bow has no colour of its own (the loops, the knot and the two tails are the apron's red), so there is no mask to trace: it is told apart from the apron only by its dark
outlines. They were read off the reference at 3x with a 20 px grid (out/franzi/bow-grid.png: the crop 600..880 x 870..1320 of ref 00, brightened), as a few points on each edge, in
canvas pixels. Each shape is a list of runs; a run is a smooth curve through its points, and the runs meet at the shape's corners (the loops' tips, the tails' corners), which stay
sharp. Written in the garment's own coordinates (x in head heights from the apron's centre line, C = 657 as in skirt_trace.py, d below the chin), so the draw maps them like the apron.
"""

from pathlib import Path

C, CHIN, H = 657.0, 434.0, 352.0

# Each shape: the runs, in order round it; a run starts where the previous one ended.
SHAPES = {
    # the long tail on the viewer's left, widening to a slanted end
    "tail_a": [
        [(727, 937), (710, 980), (702, 1013), (695, 1057), (690, 1123), (688, 1170), (687, 1250)],
        [(687, 1250), (747, 1298)],
        [(747, 1298), (745, 1200), (742, 1100), (738, 1000), (735, 950), (733, 937)],
    ],
    # the shorter tail beside it, to the right
    "tail_b": [
        [(748, 937), (750, 970), (757, 1070), (763, 1170), (773, 1259)],
        [(773, 1259), (823, 1210)],
        [(823, 1210), (813, 1137), (800, 1043), (787, 980), (768, 950), (752, 936)],
    ],
    # the two loops, each a triangle from the knot to a tip and a lower point
    "loop_l": [
        [(724, 896), (700, 903), (678, 915), (660, 935), (652, 955)],
        [(652, 955), (665, 975), (690, 998)],
        [(690, 998), (705, 985), (715, 965), (726, 940), (730, 928)],
    ],
    "loop_r": [
        [(745, 898), (775, 908), (800, 925), (820, 942)],
        [(820, 942), (797, 980)],
        [(797, 980), (780, 967), (767, 947), (755, 932), (748, 925)],
    ],
    # the knot over them
    "knot": [
        [(718, 897), (735, 892)],
        [(735, 892), (752, 898)],
        [(752, 898), (750, 915), (745, 933)],
        [(745, 933), (730, 935)],
        [(730, 935), (727, 920), (718, 897)],
    ],
}


def pt(p):
    return f"[{(p[0] - C) / H:.4f}, {(p[1] - CHIN) / H:.4f}]"


body = ""
for name, runs in SHAPES.items():
    body += f"  {name}: [\n" + "".join(f"    [{', '.join(pt(p) for p in run)}],\n" for run in runs) + "  ],\n"
Path("ts/src/body-adult-bow-data.ts").write_text(
    "// Generated by harness/franzi/bow_trace.py from the apron's bow in ref 00. Do not edit by hand.\n"
    "// Each shape is a list of runs ([x, d] points, x in head heights from the apron's centre line, d below the chin); a run is a smooth curve and the runs meet at the shape's corners.\n"
    "// Drawn in the order given, back to front.\n\n"
    "export type Run = readonly (readonly [number, number])[];\n\n"
    "export const ADULT_BOW: Readonly<Record<string, readonly Run[]>> = {\n" + body + "};\n"
)
print("wrote ts/src/body-adult-bow-data.ts")
