"""Trace the dirndl bodice of ref 03 (segment layers green-corset.png and gold-buttons-N.png) into ts/src/body-adult-bodice-data.ts.

    PYTHONPATH=.claude/skills/trace-reference ./harness/run.sh harness/franzi/bodice_trace.py

Same method as blouse_trace.py. The corset layer is the bodice's silhouette: two shoulder straps, the scooped neckline that shows the blouse, the sides that nip in at the waist and flare to the hips, and a
hem with a notch at the front. It is made symmetric by tracing the viewer's left half and mirroring it about the centre line (C = 655.5, the middle of the two columns of buttons), eroded 3 px so the
line sits on the centre of our stroke. The sixteen buttons are the centres and radii of the sixteen gold-button layers: two columns of eight, each column's x on the left, as [v, d] with v the distance
from the centre line (the other column is the mirror image). The lacing between them is drawn from the buttons in the TypeScript (each button to the next row's button on the other side).
Coordinates are the body's own: x in head heights from the garment's centre line, d in head heights below the chin. Writes out/franzi/bodice.json and the TypeScript data.
"""

import glob
import json
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

sys.path.insert(0, ".claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402

OUT = Path("out/franzi")
CHIN, H = 434.0, 352.0
SEG = "ref/franzi/segments/03-bodice/"
mask0 = np.array(Image.open(SEG + "green-corset.png"))[..., 3] > 128
C = 655.5
Ci = int(round(C))

buttons = []
for f in sorted(glob.glob(SEG + "gold-buttons/*.png")):
    m = np.array(Image.open(f))[..., 3] > 128
    ys, xs = np.nonzero(m)
    buttons.append((float(xs.mean()), float(ys.mean()), float(np.sqrt(m.sum() / np.pi))))
left = sorted([b for b in buttons if b[0] < C], key=lambda b: b[1])
right = sorted([b for b in buttons if b[0] >= C], key=lambda b: b[1])
assert len(left) == 8 and len(right) == 8
# one column serves both: the mean of the left column and the mirror of the right one, row by row
col = [(((C - l[0]) + (r[0] - C)) / 2 / H, ((l[1] + r[1]) / 2 - CHIN) / H) for l, r in zip(left, right)]
radius = float(np.mean([b[2] for b in buttons])) / H
print("buttons: v", [round(v, 3) for v, _ in col], "d", [round(d, 3) for _, d in col], "radius", round(radius, 4))

mask = ndimage.binary_fill_holes(mask0)
lab, n = ndimage.label(mask)
sizes = ndimage.sum(mask, lab, range(1, n + 1))
mask = lab == (1 + int(np.argmax(sizes)))
m = ndimage.binary_erosion(mask, iterations=3)
half = m.copy()
half[:, Ci:] = False
src = np.clip(np.round(2 * C - np.arange(m.shape[1])).astype(int), 0, m.shape[1] - 1)
sym = half | half[:, src]
# As the blouse's (blouse_trace.py): the corset of ref 03 is traced on a figure that stands a little differently from ours, and where it is slimmer than our torso the body's outline would show beside it.
# Each row's outer edge below the arms is widened, outwards only, to the body's own side (TORSO_SIDE) plus MARGIN; a row far narrower than that (the hem's curve) is left.
MARGIN = 0.005
body = open("ts/src/body-adult-data.ts").read()
mm = re.search(r"export const TORSO_SIDE[^=]*=\s*(\[\[.*?\]\]);", body, re.S)
TS = np.array(json.loads(mm.group(1)))
widened = 0
for row in range(int(CHIN + 1.1 * H), int(CHIN + 1.8 * H)):
    d = (row - CHIN) / H
    vmin = float(np.interp(d, TS[:, 0], TS[:, 1]))
    cols = np.nonzero(sym[row, Ci:])[0]
    if len(cols) == 0:
        continue
    need = int(np.ceil((vmin + MARGIN) * H))
    have = int(cols.max())
    if have < need and need - have <= 0.06 * H:
        sym[row, Ci + have : Ci + need + 1] = True
        sym[row, max(0, Ci - need - 1) : Ci - have + 1] = True
        widened += 1
print("rows widened to the body's side:", widened)
sym = ndimage.gaussian_filter(sym.astype(float), 1.5) > 0.45
np.save(OUT / "bodice_mask.npy", sym)
pts = [((x - C) / H, (y - CHIN) / H) for x, y in tl.boundary(sym)]
start, segs = tl.fit_closed(pts, 0.0035)
xs_ = [p[0] for p in pts]
ds_ = [p[1] for p in pts]
print("bodice x", round(min(xs_), 3), round(max(xs_), 3), "d", round(min(ds_), 3), round(max(ds_), 3), "segments", len(segs))
json.dump({"bodice": (start, segs), "buttons": col, "radius": radius}, open(OUT / "bodice.json", "w"), default=lambda o: list(o))


def pt(p):
    return f"[{p[0]:.4f}, {p[1]:.4f}]"


body = ", ".join(f"[{pt(c)}, {pt(e)}]" for c, e in segs)
Path("ts/src/body-adult-bodice-data.ts").write_text(
    "// Generated by harness/franzi/bodice_trace.py from the corset and button layers of ref 03. Do not edit by hand.\n"
    "// Points are [x, d]: x in head heights from the garment's centre line, d in head heights below the chin; the outline is symmetric.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    f"/** The bodice's silhouette: straps, scooped neckline, sides and hem. */\nexport const ADULT_BODICE: Chain = [{pt(start)}, [{body}]];\n\n"
    "/** One column of the eight buttons, [v, d]: v the distance from the centre line (the other column is the mirror image), d below the chin. */\n"
    "export const BODICE_BUTTONS: readonly (readonly [number, number])[] = [" + ", ".join(pt(b) for b in col) + "];\n\n"
    f"/** A button's radius in head heights. */\nexport const BODICE_BUTTON_R = {radius:.4f};\n"
)
print("wrote ts/src/body-adult-bodice-data.ts")
