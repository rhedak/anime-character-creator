"""Trace the dirndl's skirt and apron from ref 00 (ref/franzi/00-base-dirndl.png) into ts/src/body-adult-skirt-data.ts.

    PYTHONPATH=.claude/skills/trace-reference ./harness/run.sh harness/franzi/skirt_trace.py

The base image has no segment layers, but its two garments are far apart in colour: the apron, its sash and its bow are dark red, the skirt dark green (and so is
the bodice, which is why only the rows from the sash down are read). Both are made from colour masks. The skirt's silhouette is the green and the red together
from the waist down: its edges are visible all the way, the arms hang beside it. The apron is the red alone. Both are made symmetric as the blouse is, by tracing the
viewer's left half and mirroring it about the skirt's centre line (the hem's two corners are on columns 362 and 952, so C = 657), and the apron's bow, which
protrudes on the right, is left out of the outline here (it is drawn separately). Coordinates are the body's own, as in blouse_trace.py: x in head heights from the garment's
centre line, d in head heights below the chin. The mask is eroded 3 px so the line sits on the centre of our stroke. Writes out/franzi/skirt.json and the TypeScript data.
"""

import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
from scipy.spatial import ConvexHull

sys.path.insert(0, ".claude/skills/trace-reference")
import trace_lib as tl  # noqa: E402

OUT = Path("out/franzi")
CHIN, H = 434.0, 352.0
im = np.array(Image.open("ref/franzi/00-base-dirndl.png").convert("RGBA")).astype(int)
R, G, B, A = im[..., 0], im[..., 1], im[..., 2], im[..., 3]
fg = A > 128
red = fg & (R > 70) & (R > 1.6 * G) & (R > 1.5 * B)
green = fg & (G > R * 1.15) & (G > B * 1.05) & (G > 35)
rows = np.arange(im.shape[0])[:, None]
TOP = 880  # the sash's top edge: above it is the bodice
C = 657.0
Ci = int(round(C))


def clean(mask, radius=3, top=TOP):
    mask = mask & (rows >= top)
    disc = np.hypot(*np.mgrid[-radius : radius + 1, -radius : radius + 1]) <= radius
    mask = ndimage.binary_closing(np.pad(mask, radius + 2), structure=disc)[radius + 2 : -(radius + 2), radius + 2 : -(radius + 2)]
    mask = ndimage.binary_fill_holes(mask)
    lab, n = ndimage.label(mask)
    sizes = ndimage.sum(mask, lab, range(1, n + 1))
    return lab == (1 + int(np.argmax(sizes)))


def hull(mask):
    """The convex hull of a mask. Both silhouettes are convex (a flare with a curved hem), and a hand in front of the corner, or the bow beside the apron, only leave dents in the
    visible edge, so the hull is the garment's true outline."""
    ys, xs = np.nonzero(mask)
    pts = np.stack([xs, ys], 1)
    hv = ConvexHull(pts).vertices
    img = Image.new("L", (mask.shape[1], mask.shape[0]), 0)
    ImageDraw.Draw(img).polygon([tuple(map(float, pts[i])) for i in hv], fill=255)
    return np.array(img) > 0


def half_symmetric(mask):
    m = ndimage.binary_erosion(mask, iterations=3)
    left = m.copy()
    left[:, Ci:] = False
    left = hull(left)
    src = np.clip(np.round(2 * C - np.arange(m.shape[1])).astype(int), 0, m.shape[1] - 1)
    sym = left | left[:, src]
    return ndimage.gaussian_filter(sym.astype(float), 6.0) > 0.5  # the hull is a polygon; this rounds its corners into the hem's curve


skirt = half_symmetric(clean(red | green, top=TOP + 14))  # starts a little under the apron's top, so none of it shows over the sash
apron = half_symmetric(clean(red & (rows >= TOP)))
np.save(OUT / "skirt_mask.npy", skirt)
np.save(OUT / "apron_mask.npy", apron)
out = {}
for name, m in (("skirt", skirt), ("apron", apron)):
    pts = [((x - C) / H, (y - CHIN) / H) for x, y in tl.boundary(m)]
    start, segs = tl.fit_closed(pts, 0.004)
    ds = [p[1] for p in pts]
    xs = [p[0] for p in pts]
    print(name, "x", round(min(xs), 3), round(max(xs), 3), "d", round(min(ds), 3), round(max(ds), 3), "segments", len(segs))
    out[name] = (start, segs)
json.dump(out, open(OUT / "skirt.json", "w"), default=lambda o: list(o))


def pt(p):
    return f"[{p[0]:.4f}, {p[1]:.4f}]"


def chain(name, c):
    start, segs = c
    return f"export const {name}: Chain = [{pt(start)}, [{', '.join(f'[{pt(cc)}, {pt(e)}]' for cc, e in segs)}]];\n"


Path("ts/src/body-adult-skirt-data.ts").write_text(
    "// Generated by harness/franzi/skirt_trace.py from the dirndl skirt and apron of ref 00. Do not edit by hand.\n"
    "// Points are [x, d]: x in head heights from the garment's centre line, d in head heights below the chin; the outlines are symmetric.\n\n"
    'import type { Chain } from "./tables.ts";\n\n'
    "/** The skirt's silhouette, from under the sash to the hem. */\n" + chain("ADULT_SKIRT", out["skirt"]) + "\n"
    "/** The apron's: its sash at the top and its hem, narrower and shorter than the skirt's. The bow is not part of it. */\n" + chain("ADULT_APRON", out["apron"])
)
print("wrote ts/src/body-adult-skirt-data.ts")
