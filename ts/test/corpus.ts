// The full corpus (`harness/ts_port/corpus/full.json`, 7,662 render cases) and its manifests.

import { createHash } from "node:crypto";
import { join } from "node:path";
import { existsSync, readFileSync } from "node:fs";
import { characterParams, faceStyle, outfit } from "../src/model.ts";
import type { CharacterParams } from "../src/params.ts";
import type { Json } from "../src/pyjson.ts";
import { loadsText } from "../src/pyjsonload.ts";
import { REPO_ROOT, loadJson } from "./fixtures.ts";

export interface RenderKw {
  id_prefix?: string;
  background?: string | null;
  metadata?: boolean;
}
export interface FullCase {
  id: string;
  params: CharacterParams;
  kw: RenderKw;
}

const HARNESS = join(REPO_ROOT, "harness/ts_port");

/** A decoded JSON value with objects turned into plain objects; ints stay `PyInt` and floats stay numbers. */
function plainObjects(v: Json | unknown): unknown {
  if (v instanceof Map) return Object.fromEntries([...v].map(([k, x]) => [k, plainObjects(x)]));
  if (Array.isArray(v)) return v.map(plainObjects);
  return v;
}

/** Python's `json.loads` of the corpus keeps `1` and `1.0` apart, which `JSON.parse` cannot. */
export function loadFullCorpus(): FullCase[] {
  const entries = loadsText(readFileSync(join(HARNESS, "corpus/full.json"), "utf8")) as Json[];
  return entries.map((e) => {
    const m = plainObjects(e) as { id: string; kw: RenderKw; p: Record<string, unknown> };
    const { outfit: o, face: f, ...top } = m.p;
    const params = characterParams({
      ...(top as Partial<CharacterParams>),
      outfit: outfit((o ?? {}) as object),
      face: faceStyle((f ?? {}) as object),
    });
    return { id: m.id, params, kw: m.kw };
  });
}

export interface FullManifest {
  header: { case_count: number; python: string };
  cases: Record<string, [string, string]>;
  errors: Record<string, [string, string]>;
}
export const loadFullManifest = (): FullManifest => loadJson<FullManifest>(join(HARNESS, "manifest/full.json"));

/** The per-stage manifest (38 MB, regenerated by `manifest_full.py build`), or `null` when it has not been built. */
export function loadFullStages(): Record<string, { skeleton: string; stages: [string, string, number][] }> | null {
  const path = join(HARNESS, "out/full-stages.json");
  return existsSync(path) ? loadJson<{ cases: Record<string, { skeleton: string; stages: [string, string, number][] }> }>(path).cases : null;
}

/** UTF-8 with `surrogatepass`, as the Python side hashes a document that holds a lone surrogate. */
export function utf8SurrogatePass(s: string): Buffer {
  const bytes: number[] = [];
  for (let i = 0; i < s.length; i++) {
    let c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff && i + 1 < s.length) {
      const d = s.charCodeAt(i + 1);
      if (d >= 0xdc00 && d <= 0xdfff) {
        c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00);
        i++;
      }
    }
    if (c < 0x80) bytes.push(c);
    else if (c < 0x800) bytes.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000) bytes.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else bytes.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
  }
  return Buffer.from(bytes);
}

export const sha256 = (s: string): string => createHash("sha256").update(utf8SurrogatePass(s)).digest("hex");
