// The full corpus (`harness/ts_port/corpus/full.json`, 7,662 render cases) and its manifests.

import { createHash } from "node:crypto";
import { join } from "node:path";
import { existsSync, readFileSync } from "node:fs";
import { REPO_ROOT, loadJson } from "./fixtures.ts";

export { paramsFromDiff, plainObjects as decodedPlain, utf8SurrogatePass, type FullCase, type RenderKw } from "../web-check/corpus-diff.ts";
import { parseFullCorpus, utf8SurrogatePass as surrogatePass } from "../web-check/corpus-diff.ts";
import type { FullCase } from "../web-check/corpus-diff.ts";

const HARNESS = join(REPO_ROOT, "harness/ts_port");

/** The full corpus, with Python's int and float kept apart. */
export const loadFullCorpus = (): FullCase[] => parseFullCorpus(readFileSync(join(HARNESS, "corpus/full.json"), "utf8"));

export interface FullManifest {
  header: { case_count: number; python: string };
  cases: Record<string, [string, string]>;
  errors: Record<string, [string, string]>;
}
export const loadFullManifest = (): FullManifest => loadJson<FullManifest>(join(HARNESS, "manifest/full.json"));

/** The per-stage manifest (38 MB, regenerated by `manifest_full.py build`), or `null` when it has not been built. */
export function loadFullStages(): Record<string, { skeleton: string; stages: [string, string, number][] }> | null {
  const path = join(HARNESS, "out/full-stages.json");
  return existsSync(path) ? loadJson<{ cases: Record<string, { skeleton: string; stages: [string, string, number][] }> }>(path).cases : null;
}

export const sha256 = (s: string): string => createHash("sha256").update(surrogatePass(s)).digest("hex");
